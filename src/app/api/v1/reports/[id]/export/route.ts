import { NextRequest, NextResponse } from "next/server";
import { handler, ApiHttpError } from "@/lib/contracts/http";
import { requireAuth } from "@/lib/auth/context";
import { db } from "@/lib/db";

interface Section {
  id: string;
  heading: string;
  body: string;
}
interface Citation {
  [id: string]: { evidenceId: string; provider: string; url: string | null; collectedAt: string; verification: string };
}

/** Export: markdown download with full citation appendix. */
export const GET = handler(async ({ req, requestId }) => {
  const ctx = await requireAuth();
  const id = req.nextUrl.pathname.split("/")[4];
  const report = await db.researchReport.findUnique({ where: { id } });
  if (!report) throw new ApiHttpError("NOT_FOUND", "Report not found.", false);
  if (report.workspaceId !== ctx.workspaceId) throw new ApiHttpError("FORBIDDEN", "Cross-tenant access denied.", false);
  const venture = await db.venture.findUnique({
    where: { id: report.ventureId },
    select: { name: true, slug: true },
  });

  const sections = JSON.parse(report.sectionsJson) as Section[];
  const citations = JSON.parse(report.citationsJson) as Citation;

  const md: string[] = [];
  md.push(`# ${report.title}`);
  md.push("");
  md.push(`_Generated by FoundrySignal AI analyst · ${report.createdAt.toISOString()} · validation: ${report.validationStatus}_`);
  md.push("");
  md.push("> This report is generated strictly from collected evidence records. Points without supporting evidence are marked as insufficient evidence. This document is research information, not investment advice.");
  md.push("");
  for (const s of sections) {
    md.push(`## ${s.heading}`);
    md.push("");
    md.push(s.body);
    md.push("");
  }
  md.push(`## Sources`);
  md.push("");
  for (const [cid, c] of Object.entries(citations)) {
    md.push(`- **[${cid}]** ${c.provider} · ${c.url ?? "no URL"} · collected ${c.collectedAt} · verification: ${c.verification}`);
  }
  md.push("");
  md.push(`---`);
  md.push(`Venture: ${venture?.name ?? report.ventureId} (${venture?.slug ?? "unknown"})`);

  return new NextResponse(md.join("\n"), {
    status: 200,
    headers: {
      "Content-Type": "text/markdown; charset=utf-8",
      "Content-Disposition": `attachment; filename="foundrysignal-report-${report.id}.md"`,
      "x-request-id": requestId,
    },
  });
});
